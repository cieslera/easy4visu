'use strict';
// Brücke zwischen Oberfläche und Hauptprozess: nur diese Funktionen sind im Fenster als window.e4 sichtbar.
const { contextBridge, ipcRenderer } = require('electron');

// Electron setzt „Error invoking remote method …: Error:“ vor die Meldung – für die Anzeige entfernen
const clean = (msg) => String(msg || '').replace(/^Error invoking remote method '[^']+': (Error: )?/, '');
const invoke = (channel) => (...args) => ipcRenderer.invoke(channel, ...args).catch((err) => {
  throw new Error(clean(err && err.message));
});
const call = (name) => invoke(`api:${name}`);
const on = (channel) => (cb) => ipcRenderer.on(channel, (e, data) => cb(data));

